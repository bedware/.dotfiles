#!/usr/bin/env bash
# Installs terminal configs (Ghostty, herdr) from this repo on macOS.
#
# Ghostty: symlinks ~/Library/Application Support/com.mitchellh.ghostty/config.ghostty
#          -> ghostty/macos.ghostty and shared.ghostty -> ghostty/shared.ghostty.
# herdr:   TOML has no includes, so ~/.config/herdr/config.toml is GENERATED from
#          herdr/shared.toml + herdr/macos.toml. Edit those, then re-run this script.
#
# Idempotent. An existing file that would be replaced is first copied to
# <name>.bak-<timestamp>.  Usage: ./install.sh [--dry-run]
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
STAMP="$(date +%Y%m%d-%H%M%S)"
DRY=0
[[ "${1:-}" == "--dry-run" ]] && DRY=1

step() { printf '  %s\n' "$*"; }
run()  { [[ $DRY -eq 1 ]] || "$@"; }

backup() {
  step "backup  $1 -> $1.bak-$STAMP"
  run cp -p "$1" "$1.bak-$STAMP"
}

install_link() { # <link> <target>
  local link="$1" target="$2"
  if [[ -L "$link" ]]; then
    if [[ "$(readlink "$link")" == "$target" ]]; then step "ok      $link"; return; fi
    step "relink  $link (was -> $(readlink "$link"))"
    run rm "$link"
  elif [[ -d "$link" ]]; then
    echo "$link is a directory; refusing to replace it." >&2; exit 1
  elif [[ -e "$link" ]]; then
    backup "$link"; run rm "$link"
  fi
  step "link    $link -> $target"
  run mkdir -p "$(dirname "$link")"
  run ln -s "$target" "$link"
}

install_generated() { # <path> <source>...
  local path="$1"; shift
  local rel="" src content
  for src in "$@"; do rel+="${rel:+ + }${src#"$REPO"/}"; done
  content="# GENERATED by ~/.dotfiles/install.sh from $rel
# Do not edit here: edit the sources and re-run the installer.
"
  local first=1
  for src in "$@"; do
    [[ $first -eq 1 ]] || content+=$'\n'
    content+=$'\n'"$(cat "$src")"
    first=0
  done
  content+=$'\n'

  if [[ -L "$path" ]]; then
    step "unlink  $path"; run rm "$path"
  elif [[ -f "$path" ]]; then
    if [[ "$(cat "$path"; printf x)" == "${content}x" ]]; then step "ok      $path"; return; fi
    backup "$path"
  fi
  step "write   $path"
  run mkdir -p "$(dirname "$path")"
  [[ $DRY -eq 1 ]] || printf '%s' "$content" > "$path"
}

echo "Fonts"
if command -v brew >/dev/null; then
  if brew list --cask font-ubuntu-mono >/dev/null 2>&1; then step "ok      font-ubuntu-mono"
  else step "install font-ubuntu-mono (brew)"; run brew install --cask font-ubuntu-mono; fi
else
  step "skip    Homebrew not found; install the Ubuntu Mono font manually"
fi

echo "Ghostty"
GHOSTTY_DIR="$HOME/Library/Application Support/com.mitchellh.ghostty"
install_link "$GHOSTTY_DIR/config.ghostty" "$REPO/ghostty/macos.ghostty"
install_link "$GHOSTTY_DIR/shared.ghostty" "$REPO/ghostty/shared.ghostty"

echo "herdr"
install_generated "$HOME/.config/herdr/config.toml" "$REPO/herdr/shared.toml" "$REPO/herdr/macos.toml"

if [[ $DRY -eq 0 ]] && command -v herdr >/dev/null; then
  herdr config check
  herdr server reload-config 2>/dev/null && step "reloaded running herdr server" || true
fi

echo "Done. Ghostty: reload config with Cmd+Shift+, (theme/font apply to new windows)."
