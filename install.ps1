#Requires -Version 7
<#
.SYNOPSIS
Installs terminal configs (Ghostty, herdr) from this repo on Windows.

.DESCRIPTION
Ghostty: symlinks %LOCALAPPDATA%\ghostty\config.ghostty -> ghostty\windows.ghostty
         and shared.ghostty -> ghostty\shared.ghostty (windows.ghostty includes it).
herdr:   TOML has no includes, so %APPDATA%\herdr\config.toml is GENERATED from
         herdr\shared.toml + herdr\windows.toml. Edit those, then re-run this script.

Idempotent. An existing file that would be replaced is first copied to
<name>.bak-<timestamp>. Symlinks need Developer Mode (or an elevated shell).

.PARAMETER DryRun
Print what would happen without changing anything.
#>
[CmdletBinding()]
param([switch]$DryRun)

$ErrorActionPreference = 'Stop'
$Repo  = $PSScriptRoot
$Stamp = Get-Date -Format 'yyyyMMdd-HHmmss'

function Write-Step($msg) { Write-Host "  $msg" }

function Backup-Item([string]$Path) {
    $bak = "$Path.bak-$Stamp"
    Write-Step "backup  $Path -> $bak"
    if (-not $DryRun) { Copy-Item -LiteralPath $Path -Destination $bak }
}

function Install-Link([string]$Link, [string]$Target) {
    $item = Get-Item -LiteralPath $Link -Force -ErrorAction SilentlyContinue
    if ($item -and $item.LinkType -eq 'SymbolicLink') {
        if ($item.Target -eq $Target) { Write-Step "ok      $Link"; return }
        Write-Step "relink  $Link (was -> $($item.Target))"
        if (-not $DryRun) { Remove-Item -LiteralPath $Link -Force }
    } elseif ($item) {
        if ($item.PSIsContainer) { throw "$Link is a directory; refusing to replace it." }
        Backup-Item $Link
        if (-not $DryRun) { Remove-Item -LiteralPath $Link -Force }
    }
    Write-Step "link    $Link -> $Target"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path $Link) | Out-Null
        New-Item -ItemType SymbolicLink -Path $Link -Target $Target | Out-Null
    }
}

function Install-Generated([string]$Path, [string[]]$Sources) {
    $rel = ($Sources | ForEach-Object { [IO.Path]::GetRelativePath($Repo, $_) -replace '\\', '/' }) -join ' + '
    $header = "# GENERATED by ~/.dotfiles/install.ps1 from $rel`n# Do not edit here: edit the sources and re-run the installer.`n"
    $body = ($Sources | ForEach-Object { (Get-Content -LiteralPath $_ -Raw).TrimEnd() }) -join "`n`n"
    $content = "$header`n$body`n"

    $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    if ($item) {
        if ($item.LinkType) { Write-Step "unlink  $Path"; if (-not $DryRun) { Remove-Item -LiteralPath $Path -Force } }
        elseif ((Get-Content -LiteralPath $Path -Raw) -replace "`r`n", "`n" -eq $content) { Write-Step "ok      $Path"; return }
        else { Backup-Item $Path }
    }
    Write-Step "write   $Path"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path $Path) | Out-Null
        [IO.File]::WriteAllText($Path, $content)
    }
}

# Plain copy for configs the app itself rewrites or resolves paths relative to
# (OpenCode's cli.json): a symlink would be replaced or point plugins at the repo.
function Install-Copy([string]$Path, [string]$Source) {
    $content = (Get-Content -LiteralPath $Source -Raw) -replace "`r`n", "`n"
    $item = Get-Item -LiteralPath $Path -Force -ErrorAction SilentlyContinue
    if ($item) {
        if ($item.LinkType) { Write-Step "unlink  $Path"; if (-not $DryRun) { Remove-Item -LiteralPath $Path -Force } }
        elseif (((Get-Content -LiteralPath $Path -Raw) -replace "`r`n", "`n") -eq $content) { Write-Step "ok      $Path"; return }
        else { Backup-Item $Path }
    }
    Write-Step "copy    $Path"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path $Path) | Out-Null
        [IO.File]::WriteAllText($Path, $content)
    }
}

Write-Host 'Ghostty'
$ghosttyDir = Join-Path $env:LOCALAPPDATA 'ghostty'
Install-Link (Join-Path $ghosttyDir 'config.ghostty') (Join-Path $Repo 'ghostty\windows.ghostty')
Install-Link (Join-Path $ghosttyDir 'shared.ghostty') (Join-Path $Repo 'ghostty\shared.ghostty')

Write-Host 'herdr'
$herdrConfig = Join-Path $env:APPDATA 'herdr\config.toml'
Install-Generated $herdrConfig @((Join-Path $Repo 'herdr\shared.toml'), (Join-Path $Repo 'herdr\windows.toml'))

Write-Host 'OpenCode'
Install-Copy (Join-Path $HOME '.config\opencode\cli.json') (Join-Path $Repo 'opencode\cli.json')

Write-Host 'Shell'
$profilePath = $PROFILE.CurrentUserCurrentHost
$hook = '. "$HOME\.dotfiles\shell\init.ps1"  # dotfiles aliases'
if ((Test-Path $profilePath) -and (Select-String -LiteralPath $profilePath -SimpleMatch 'dotfiles\shell\init.ps1' -Quiet)) {
    Write-Step "ok      $profilePath"
} else {
    Write-Step "append  $profilePath <- $hook"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path $profilePath) | Out-Null
        Add-Content -LiteralPath $profilePath -Value "`n$hook"
    }
}

$herdr = (Get-Command herdr -ErrorAction SilentlyContinue)?.Source
if (-not $herdr) { $herdr = Join-Path $env:LOCALAPPDATA 'Programs\Herdr\bin\herdr.exe' }
if (-not $DryRun -and (Test-Path $herdr)) {
    & $herdr config check
    & $herdr server reload-config *> $null
    if ($LASTEXITCODE -eq 0) { Write-Step 'reloaded running herdr server' }
    else { Write-Step 'herdr server not reloaded (not running or elevated): press prefix+shift+r inside herdr' }
}

Write-Host 'Done. Ghostty: reload config with Ctrl+Shift+, (theme/font apply to new windows).'
